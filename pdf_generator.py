                n_en = str(it.get("Nutrient (EN)") or it.get("name_en") or it.get("nutrient_en") or "").strip()
                amt = str(it.get("Jumlah (Amount)") or it.get("amount") or it.get("Jumlah") or "").strip()
                dv = str(it.get("% AKG / DV") or it.get("daily_value") or it.get("AKG") or "").strip()
                
                # Lewati baris energi karena sudah dicetak khusus di Seksi Amount Per Serving
