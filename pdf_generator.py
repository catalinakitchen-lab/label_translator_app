    c.restoreState()

    # Siapkan baris dengan wrapping teks nama nutrisi
    target_r_fs = 3.8 * sy * s4_scale
    prep_items = []
    for r_item in all_items:
        if isinstance(r_item, (list, tuple)) and len(r_item) >= 2:
            r_name = str(r_item[0]).upper().strip()
            r_amt = str(r_item[1]).upper().strip()
            r_dv = str(r_item[2]).upper().strip() if len(r_item) > 2 else ""
        else:
            continue
        lines = simpleSplit(r_name, active_font, target_r_fs, col_name_w / 0.70)
        if len(lines) > 2:
            lines = lines[:2]
        prep_items.append((lines, r_amt, r_dv))

    total_lines = sum(len(p[0]) for p in prep_items)
    row_y = hdr_dv_y - (4.6 * sy)
    avail_tbl_h = max(row_y - div3_y - (1.5 * sy), 10.0 * sy)
    max_r_lh = 8.0 * sy * s4_scale * table_height_scale
    r_lh = min(max_r_lh, avail_tbl_h / max(total_lines, 1))
    r_fs = min(4.5 * sy * s4_scale, r_lh * 0.78)

    for lines, r_amt, r_dv in prep_items:
        # Kolom 1: Nama Zat Gizi
        c.saveState()
        t_r = c.beginText(col_name_x, row_y)
        t_r.setFont(active_font, r_fs)
        t_r.setHorizScale(70.0)
        for l in lines:
            t_r.textLine(l)
        c.drawText(t_r)
        c.restoreState()

        # Kolom 2: Jumlah / Kandungan per Sajian (Amount) - Rata kiri pada 50.5
        c.saveState()
        t_ra = c.beginText(col_amt_x, row_y)
        t_ra.setFont(active_font, r_fs)
        t_ra.setHorizScale(70.0)
        t_ra.textOut(r_amt)
        c.drawText(t_ra)
        c.restoreState()

        # Kolom 3: % AKG / % DV - Rata kanan pada 79.5
        if r_dv and r_dv not in ["-", ""]:
            c.saveState()
            c.setFont(active_font, r_fs)
            c.drawRightString(col_dv_x, row_y, r_dv)
            c.restoreState()

        row_y -= (len(lines) * r_lh)

    # Footer Distributor (Outside box at bottom)
    if distributor_info or distributor_header:
        c.saveState()
        d_scale = font_scale * font_scale_dist
        d_fs = 4.6 * sy * d_scale
        d_lh = 5.2 * sy * d_scale
        d_top_pad = 5.8 * sy * d_scale
        d_y = box_y - d_top_pad
        
        t_dist = c.beginText(3.7 * sx, d_y)
        t_dist.setFont(active_font, d_fs)
        t_dist.setLeading(d_lh)
        t_dist.setHorizScale(85.0)
        
        if distributor_header:
            t_dist.textLine(distributor_header.upper().strip())
        for d_line in distributor_info.strip().split("\n"):
            d_clean = d_line.strip().upper()
            if d_clean:
                t_dist.textLine(d_clean)
                
        c.drawText(t_dist)
        c.restoreState()


    c.showPage()
    c.save()
    return buf.getvalue()


