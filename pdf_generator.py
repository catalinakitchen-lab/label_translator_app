GOTHAM_FONT_NAME = "GothamOffice-Bold"

def register_gotham_font() -> str:
    """
    Mendaftarkan font GothamOffice-Bold ke ReportLab jika belum terdaftar.
    """
    if GOTHAM_FONT_NAME in pdfmetrics.getRegisteredFontNames():
        return GOTHAM_FONT_NAME
        
    font_paths = [
        Path(__file__).parent / "fonts" / "GothamOffice-Bold.ttf",
        Path("C:/Users/USER03/AppData/Local/Microsoft/Windows/Fonts/FontsFree-Net-GothamOffice-Bold.ttf"),
        Path("C:/Windows/Fonts/GothamOffice-Bold.ttf")
    ]
    for fp in font_paths:
        if fp.exists():
            try:
                pdfmetrics.registerFont(TTFont(GOTHAM_FONT_NAME, str(fp)))
                return GOTHAM_FONT_NAME
            except Exception as e:
                print(f"Error registering font from {fp}: {e}")
                
    return "Helvetica-Bold"  # Fallback jika file tidak ditemukan

class NumberedCanvas(canvas.Canvas):
    """
    Canvas kustom untuk menghitung total halaman secara dinamis
    dan menambahkan footer 'Halaman X dari Y' serta garis pemisah.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor('#64748B'))
        
        # Garis footer
        self.setStrokeColor(colors.HexColor('#CBD5E1'))
        self.setLineWidth(0.5)
        self.line(36, 32, self._pagesize[0] - 36, 32)
        
        # Teks Footer
        doc_info = "Generated by Label Packaging Translator App | Dokumen Referensi Label Kemasan"
        self.drawString(36, 20, doc_info)
        
        page_str = f"Halaman {self._pageNumber} dari {page_count}"
        self.drawRightString(self._pagesize[0] - 36, 20, page_str)
        self.restoreState()


def build_bilingual_label_pdf(
    product_name: str,
    indonesian_text: str,
    english_text: str,
    image_bytes: bytes = None,
    company_name: str = "CV LINTAS TUJUH BENUA",
    company_subtitle: str = "Export | Import Documentation",
    company_logo_bytes: bytes = None,
    variant: str = "-",
    net_weight: str = "-",
    allergen_note_id: str = "",
    allergen_note_en: str = "",
    page_size_choice: str = "A4"
) -> bytes:
    """
    Menghasilkan file PDF bilingual dalam bentuk bytes buffer.
    """
    buffer = io.BytesIO()
    
    pagesize = A4 if page_size_choice == "A4" else letter
    page_width, page_height = pagesize
    
    margin = 36  # 0.5 inch
    content_width = page_width - (2 * margin)

    doc = SimpleDocTemplate(
        buffer,
        pagesize=pagesize,
        rightMargin=margin,
        leftMargin=margin,
        topMargin=36,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    # Kustomisasi gaya teks
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=16,
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=3,
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        textColor=colors.HexColor('#475569'),
        spaceAfter=12,
    )

    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=11,
        textColor=colors.HexColor('#1E3A8A'),
        spaceBefore=8,
        spaceAfter=6,
    )

    col_title_id = ParagraphStyle(
        'ColTitleID',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=10,
        textColor=colors.HexColor('#1E40AF'),
        spaceAfter=6,
    )

    col_title_en = ParagraphStyle(
        'ColTitleEN',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=10,
        textColor=colors.HexColor('#065F46'),
        spaceAfter=6,
    )

    cell_body = ParagraphStyle(
        'CellBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13.5,
        textColor=colors.HexColor('#1E293B'),
    )

    allergen_style_id = ParagraphStyle(
        'AllergenID',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor('#991B1B'),
    )

    allergen_style_en = ParagraphStyle(
        'AllergenEN',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor('#991B1B'),
    )

    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#64748B'),
    )

    elements = []

    # 1. Header Banner
    if company_logo_bytes:
        try:
            logo_img = RLImage(io.BytesIO(company_logo_bytes), width=42, height=42)
            comp_text = Paragraph(
                f"<b>{company_name}</b><br/><font size=8 color='#64748B'>{company_subtitle}</font>",
                ParagraphStyle('Comp', parent=styles['Normal'], alignment=2, fontName='Helvetica', fontSize=9, textColor=colors.HexColor('#1E3A8A'), leading=12)
            )
            comp_cell = Table([[comp_text, logo_img]], colWidths=[content_width * 0.35 - 48, 48])
            comp_cell.setStyle(TableStyle([
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                ('ALIGN', (0,0), (0,0), 'RIGHT'),
                ('ALIGN', (1,0), (1,0), 'RIGHT'),
                ('LEFTPADDING', (0,0), (-1,-1), 0),
                ('RIGHTPADDING', (0,0), (-1,-1), 0),
                ('TOPPADDING', (0,0), (-1,-1), 0),
                ('BOTTOMPADDING', (0,0), (-1,-1), 0),
            ]))
        except Exception:
            comp_cell = Paragraph(
                f"<b>{company_name}</b><br/><font size=8 color='#64748B'>{company_subtitle}</font>",
                ParagraphStyle('Comp', parent=styles['Normal'], alignment=2, fontName='Helvetica', fontSize=9, textColor=colors.HexColor('#1E3A8A'), leading=12)
            )
    else:
        comp_cell = Paragraph(
            f"<b>{company_name}</b><br/><font size=8 color='#64748B'>{company_subtitle}</font>",
            ParagraphStyle('Comp', parent=styles['Normal'], alignment=2, fontName='Helvetica', fontSize=9, textColor=colors.HexColor('#1E3A8A'), leading=12)
        )

    header_data = [
        [
            Paragraph("<b>SPESIFIKASI & TERJEMAHAN LABEL KEMASAN</b><br/><font size=9 color='#64748B'>Packaging Ingredient Label & Bilingual Specification Sheet</font>", title_style),
            comp_cell
        ]
    ]
    header_table = Table(header_data, colWidths=[content_width * 0.65, content_width * 0.35])
    header_table.setStyle(TableStyle([
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('BOTTOMPADDING', (0,0), (-1,-1), 0),
        ('TOPPADDING', (0,0), (-1,-1), 0),
    ]))
    elements.append(header_table)
    elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#1D4ED8'), spaceBefore=8, spaceAfter=10))

    # 2. Metadata Table
    today_str = datetime.now().strftime("%d %B %Y")
    meta_data = [
        [
            Paragraph(f"<b>Nama Produk / Product:</b> {product_name or 'N/A'}", cell_body),
            Paragraph(f"<b>Tanggal / Date:</b> {today_str}", cell_body)
        ],
        [
            Paragraph(f"<b>Varian / Netto:</b> {variant} | {net_weight}", cell_body),
            Paragraph(f"<b>Bahasa:</b> Indonesia (ID) &rarr; English (EN)", cell_body)
        ]
    ]
    meta_table = Table(meta_data, colWidths=[content_width * 0.5, content_width * 0.5])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('BOX', (0,0), (-1,-1), 0.8, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0,0), (-1,-1), 0.4, colors.HexColor('#E2E8F0')),
        ('TOPPADDING', (0,0), (-1,-1), 5),
        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
        ('LEFTPADDING', (0,0), (-1,-1), 8),
        ('RIGHTPADDING', (0,0), (-1,-1), 8),
    ]))
    elements.append(meta_table)
    elements.append(Spacer(1, 10))

    # 3. Product Label Image (if available)
    if image_bytes:
        try:
            img_stream = io.BytesIO(image_bytes)
            pil_img = Image.open(img_stream)
            orig_w, orig_h = pil_img.size
            
            # Hitung skala agar pas di halaman (max lebar 5.2 inch, max tinggi 2.2 inch)
            max_img_w = content_width * 0.85
            max_img_h = 2.0 * inch
            
            scale = min(max_img_w / orig_w, max_img_h / orig_h, 1.0)
            target_w = orig_w * scale
            target_h = orig_h * scale
            
            img_stream.seek(0)
            rl_img = RLImage(img_stream, width=target_w, height=target_h)
            
            img_container = Table(
                [[rl_img]],
                colWidths=[content_width]
            )
            img_container.setStyle(TableStyle([
                ('ALIGN', (0,0), (-1,-1), 'CENTER'),
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F1F5F9')),
                ('BOX', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
                ('TOPPADDING', (0,0), (-1,-1), 6),
                ('BOTTOMPADDING', (0,0), (-1,-1), 6),
            ]))
            
            elements.append(Paragraph("<b>Foto / Sampel Label Kemasan:</b>", section_heading))
            elements.append(img_container)
            elements.append(Spacer(1, 10))
        except Exception as e:
            print(f"Error embedding image to PDF: {e}")

    # 4. Bilingual Comparison Table
    elements.append(Paragraph("<b>Tabel Perbandingan Komposisi (Bilingual Composition Table):</b>", section_heading))

    formatted_id = indonesian_text.replace('\n', '<br/>')
    formatted_en = english_text.replace('\n', '<br/>')

    col_id_cell = [
        Paragraph("<b>BAHASA INDONESIA (ASLI)</b>", col_title_id),
        HRFlowable(width="100%", thickness=0.8, color=colors.HexColor('#93C5FD'), spaceBefore=2, spaceAfter=6),
        Paragraph(formatted_id, cell_body)
    ]

    col_en_cell = [
        Paragraph("<b>ENGLISH (TRANSLATION)</b>", col_title_en),
        HRFlowable(width="100%", thickness=0.8, color=colors.HexColor('#86EFAC'), spaceBefore=2, spaceAfter=6),
        Paragraph(formatted_en, cell_body)
    ]

    half_w = (content_width - 6) / 2
    bilingual_table = Table(
        [[col_id_cell, col_en_cell]],
        colWidths=[half_w, half_w]
    )
    bilingual_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (0,0), colors.HexColor('#F8FAFC')),
        ('BACKGROUND', (1,0), (1,0), colors.HexColor('#F0FDF4')),
        ('BOX', (0,0), (0,0), 1, colors.HexColor('#93C5FD')),
        ('BOX', (1,0), (1,0), 1, colors.HexColor('#86EFAC')),
        ('TOPPADDING', (0,0), (-1,-1), 8),
        ('BOTTOMPADDING', (0,0), (-1,-1), 8),
        ('LEFTPADDING', (0,0), (-1,-1), 8),
        ('RIGHTPADDING', (0,0), (-1,-1), 8),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
    ]))
    elements.append(bilingual_table)
    elements.append(Spacer(1, 10))

    # 5. Peringatan Alergen Callout (Jika ada)
    if allergen_note_id or allergen_note_en:
        allergen_cell_id = Paragraph(f"<b>PERINGATAN ALERGEN:</b><br/>{allergen_note_id}", allergen_style_id)
        allergen_cell_en = Paragraph(f"<b>ALLERGEN ADVICE:</b><br/>{allergen_note_en}", allergen_style_en)
        allergen_table = Table(
            [[allergen_cell_id, allergen_cell_en]],
            colWidths=[half_w, half_w]
        )
        allergen_table.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#FEF2F2')),
            ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#FCA5A5')),
            ('TOPPADDING', (0,0), (-1,-1), 6),
            ('BOTTOMPADDING', (0,0), (-1,-1), 6),
            ('LEFTPADDING', (0,0), (-1,-1), 8),
            ('RIGHTPADDING', (0,0), (-1,-1), 8),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ]))
        elements.append(allergen_table)
        elements.append(Spacer(1, 10))

    # 6. Catatan Legal / Regulasi
    disclaimer_text = (
        "<b>Catatan Kepatuhan Regulasi (Compliance Note):</b> Terjemahan ini disiapkan sebagai referensi teknis "
        "label pangan untuk keperluan administrasi, ekspor, dan pencocokan bahan baku. Silakan lakukan verifikasi "
        "akhir sesuai regulasi otoritas pangan setempat (Badan POM RI, US FDA, EFSA, atau otoritas negara tujuan ekspor)."
    )
    elements.append(Paragraph(disclaimer_text, disclaimer_style))

    # Bangun PDF dengan NumberedCanvas
    doc.build(elements, canvasmaker=NumberedCanvas)
    
    buffer.seek(0)
    return buffer.getvalue()


def build_sticker_label_pdf(
    product_name: str,
    net_weight: str,
    ingredients_text: str,
    distributor_header: str = "",
    distributor_info: str = "LOLLO WHOLESALE\n7505071 / 3395050\nSALES@LOLLO.MV",
    size_choice: str = "4x6 cm",
    custom_width_mm: float = 40.0,
    custom_height_mm: float = 60.0,
    orientation: str = "portrait",
    uppercase: bool = True,
    manual_font_scale: float = 1.0,
    font_scale_title: float = 1.0,
    font_scale_body: float = 1.0,
    font_scale_dist: float = 1.0,
    margin_left_mm: float = 2.5,
    margin_right_mm: float = 2.5,
    margin_top_mm: float = 3.0,
    margin_bottom_mm: float = 2.5,
    show_border: bool = False,
    border_style: str = "Garis Lurus (Solid)",
    border_thickness: float = 0.6,
    border_inset_mm: float = 1.5,
    border_color: str = "Hitam Pekat",
    font_family: str = "GothamOffice-Bold",
    include_company_logo: bool = False,
    company_logo_bytes: bytes = None,
    logo_position: str = "top"
) -> bytes:
    """
    Menghasilkan file PDF label stiker kemasan (seperti format Milo Cube / label stiker impor/ekspor).
    Mendukung ukuran 3x5 cm, 4x6 cm, 3x5 inch, 4x6 inch, atau ukuran kustom.
    Menggunakan font GothamOffice-Bold dan auto-fit 1 halaman.
    """
    # Daftarkan dan aktifkan font GothamOffice-Bold
    active_font = register_gotham_font() if font_family == "GothamOffice-Bold" else "Helvetica-Bold"

    # 1. Tentukan dimensi halaman
    if size_choice == "3x5 cm":
        pw, ph = 3.0 * cm, 5.0 * cm
    elif size_choice == "4x6 cm":
        pw, ph = 4.0 * cm, 6.0 * cm
    elif size_choice == "5x7 cm":
        pw, ph = 5.0 * cm, 7.0 * cm
    elif size_choice == "3x5 inch":
        pw, ph = 3.0 * inch, 5.0 * inch
    elif size_choice == "4x6 inch":
        pw, ph = 4.0 * inch, 6.0 * inch
    elif size_choice == "custom":
        pw = (custom_width_mm / 10.0) * cm
        ph = (custom_height_mm / 10.0) * cm
    else:
        pw, ph = 4.0 * cm, 6.0 * cm

    if orientation == "landscape":
        pw, ph = max(pw, ph), min(pw, ph)
    else:
        pw, ph = min(pw, ph), max(pw, ph)

    # 2. Persiapkan teks (uppercase jika dipilih)
    p_name = product_name.strip()
    p_weight = net_weight.strip()
    ing_text = ingredients_text.strip()
    dist_hdr = distributor_header.strip()
    dist_info = distributor_info.strip()

    if uppercase:
        p_name = p_name.upper()
        p_weight = p_weight.upper()
        ing_text = ing_text.upper()
        dist_hdr = dist_hdr.upper()
        dist_info = dist_info.upper()

    # Gabungkan nama produk dan netto di baris atas
    header_parts = []
    if p_name:
        header_parts.append(p_name)
    if p_weight:
        header_parts.append(p_weight)
    title_combined = "<br/>".join(header_parts)

    formatted_ing = ing_text.replace("\n", " ").strip()
    formatted_dist = dist_info.replace("\n", "<br/>").strip()

    # 3. Hitung proporsi font dasar sesuai lebar label
    ref_w = min(pw, ph)
    base_title_fs = (ref_w / (4.0 * cm)) * 9.5
    base_sec_fs = (ref_w / (4.0 * cm)) * 8.0
    base_body_fs = (ref_w / (4.0 * cm)) * 6.8
    base_dist_fs = (ref_w / (4.0 * cm)) * 7.5
    # Konversi margin mm ke points (1 mm = 72 / 25.4 pt)
    ml_pt = (float(margin_left_mm) / 25.4) * 72.0
    mr_pt = (float(margin_right_mm) / 25.4) * 72.0
    mt_pt = (float(margin_top_mm) / 25.4) * 72.0
    mb_pt = (float(margin_bottom_mm) / 25.4) * 72.0

    # Daftar skala untuk dicoba (auto-fit ke 1 halaman)
    scales_to_try = [
        manual_font_scale * 1.0,
        manual_font_scale * 0.95,
        manual_font_scale * 0.90,
        manual_font_scale * 0.85,
        manual_font_scale * 0.80,
        manual_font_scale * 0.75,
        manual_font_scale * 0.70,
        manual_font_scale * 0.65,
        manual_font_scale * 0.60,
        manual_font_scale * 0.55,
        manual_font_scale * 0.50,
        manual_font_scale * 0.45,
    ]

    best_pdf = None

    for sc in scales_to_try:
        cur_ml = ml_pt * max(0.85, sc)
        cur_mr = mr_pt * max(0.85, sc)
        cur_mt = mt_pt * max(0.85, sc)
        cur_mb = mb_pt * max(0.85, sc)
        buf = io.BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=(pw, ph),
            leftMargin=cur_ml,
            rightMargin=cur_mr,
            topMargin=cur_mt,
            bottomMargin=cur_mb
        )

        f_t = base_title_fs * sc * font_scale_title
        f_s = base_sec_fs * sc * font_scale_body
        f_b = base_body_fs * sc * font_scale_body
        f_d = base_dist_fs * sc * font_scale_dist

        l_t = f_t * 1.25
        l_s = f_s * 1.25
        l_b = f_b * 1.25
        l_d = f_d * 1.25

        st_title = ParagraphStyle(
            'StkTitle',
            fontName=active_font,
            fontSize=f_t,
            leading=l_t,
            textColor=colors.black,
            spaceAfter=0
        )
        st_sec = ParagraphStyle(
            'StkSec',
            fontName=active_font,
            fontSize=f_s,
            leading=l_s,
            textColor=colors.black,
            spaceAfter=0
        )
        st_body = ParagraphStyle(
            'StkBody',
            fontName=active_font,
            fontSize=f_b,
            leading=l_b,
            textColor=colors.black,
            spaceAfter=0
        )
        st_dist = ParagraphStyle(
            'StkDist',
            fontName=active_font,
            fontSize=f_d,
            leading=l_d,
            textColor=colors.black,
            spaceAfter=0
        )

        spacer_large = max(2, (ref_w * 0.045) * sc)
        spacer_small = max(1, (ref_w * 0.02) * sc)

        logo_flowable = None
        if include_company_logo and company_logo_bytes:
            try:
                l_sz = max(14.0, min(ref_w * 0.22, 28.0) * sc)
                logo_flowable = RLImage(io.BytesIO(company_logo_bytes), width=l_sz, height=l_sz)
                logo_flowable.hAlign = 'CENTER'
            except Exception:
                logo_flowable = None

        story = []

        # Logo di Bagian Atas
        if logo_flowable and logo_position == "top":
            story.append(logo_flowable)
            story.append(Spacer(1, spacer_small))

        # Blok 1: Nama Produk & Berat
        if title_combined:
            story.append(Paragraph(title_combined, st_title))
            story.append(Spacer(1, spacer_large))

        # Blok 2: Komposisi / INGREDIENTS
        if formatted_ing:
            story.append(Paragraph("INGREDIENTS :", st_sec))
            story.append(Spacer(1, spacer_small))
            story.append(Paragraph(formatted_ing, st_body))
            story.append(Spacer(1, spacer_large))

        # Logo di Bagian Bawah
        if logo_flowable and logo_position == "bottom":
            story.append(Spacer(1, spacer_small))
            story.append(logo_flowable)
            story.append(Spacer(1, spacer_small))

        # Blok 3: IMPORTED BY / DISTRIBUTED BY
        if dist_hdr or formatted_dist:
            if dist_hdr:
                story.append(Paragraph(dist_hdr, st_dist))
            if formatted_dist:
                story.append(Paragraph(formatted_dist, st_dist))

        try:
            doc.build(story)
            candidate_pdf = buf.getvalue()
            doc_fitz = pymupdf.open(stream=candidate_pdf, filetype="pdf")
            if len(doc_fitz) == 1:
                best_pdf = candidate_pdf
                break
            else:
                # Masih lebih dari 1 halaman, coba skala lebih kecil
                best_pdf = candidate_pdf
        except Exception:
            continue

    if best_pdf is None:
        best_pdf = candidate_pdf

    # Jika pengguna meminta border luar stiker
    if show_border and best_pdf:
        try:
            doc_fitz = pymupdf.open(stream=best_pdf, filetype="pdf")
            page = doc_fitz[0]
            rect = page.rect
            shape = page.new_shape()

            # Konversi border_inset_mm ke points (1 mm = 72 / 25.4 points ≈ 2.83465 pt)
            inset_pt = (float(border_inset_mm) / 25.4) * 72.0
            inset_pt = min(inset_pt, min(rect.width, rect.height) * 0.25)

            # Tentukan warna
            if "Abu-abu Gelap" in str(border_color):
                col = (0.28, 0.33, 0.41)
            elif "Abu-abu Terang" in str(border_color):
                col = (0.80, 0.84, 0.88)
            else:
                col = (0.0, 0.0, 0.0) # Hitam Pekat

            # Tentukan gaya garis (dashes)
            if "Putus-putus" in str(border_style) or "Dashed" in str(border_style):
                dash_str = "[4 3] 0"
            elif "Titik-titik" in str(border_style) or "Dotted" in str(border_style):
                dash_str = "[1.2 2.5] 0"
            else:
                dash_str = None

            shape.draw_rect(pymupdf.Rect(inset_pt, inset_pt, rect.width - inset_pt, rect.height - inset_pt))
            shape.finish(color=col, width=float(border_thickness), dashes=dash_str)
            shape.commit()
            best_pdf = doc_fitz.tobytes()
        except Exception as e:
            print(f"Error drawing sticker border: {e}")

    return best_pdf


def pdf_to_preview_image(pdf_bytes: bytes, dpi: int = 180) -> bytes:
    """
    Mengonversi halaman pertama PDF menjadi gambar PNG (bytes)
    untuk ditampilkan langsung sebagai pratinjau di Streamlit.
    """
    if not pdf_bytes:
        return None
    try:
        doc = pymupdf.open(stream=pdf_bytes, filetype="pdf")
        if len(doc) > 0:
            page = doc[0]
            pix = page.get_pixmap(dpi=dpi)
            return pix.tobytes("png")
    except Exception as e:
        print(f"Error rendering PDF to image preview: {e}")
    return None


