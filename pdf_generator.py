                if language_choice == "indonesian":
                    name_disp = n_id if n_id else n_en
                elif language_choice == "bilingual":
                    name_disp = f"{n_id} / {n_en}" if (n_id and n_en and n_id.strip().lower() != n_en.strip().lower()) else (n_en or n_id)
