    hdr_fs = 6.2 * sy * s1_scale
    c.saveState()
    hdr_text = (header_text or "INGREDIENTS & NUTRITIONAL INFORMATION").upper().strip()
    raw_w = c.stringWidth(hdr_text, active_font, hdr_fs)
    avail_w = 74.0 * sx
