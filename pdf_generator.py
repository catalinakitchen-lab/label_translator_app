    box_w = 77.85 * sx
    box_top = 126.75 * sy
    base_box_h = 101.75 * sy
    box_h = base_box_h * table_height_scale
    has_dist = bool((distributor_info and str(distributor_info).strip()) or (distributor_header and str(distributor_header).strip()))
    if has_dist:
        dist_lines_count = (1 if distributor_header else 0) + len([l for l in (distributor_info or "").strip().splitlines() if l.strip()])
        dist_needed_h = (dist_lines_count * 5.2 * sy * font_scale_dist) + (6.0 * sy)
        dist_reserved = max(16.0 * sy, dist_needed_h)
    else:
        dist_reserved = 4.0 * sy
    min_box_y = dist_reserved
    box_y = max(min_box_y, box_top - box_h)
    box_h = box_top - box_y
    c.rect(box_x, box_y, box_w, box_h, stroke=1, fill=0)

    # 2. Product Name (Centered at top outside box - Sesi 1)
    s1_scale = font_scale * font_scale_s1
    p_name = product_name.upper().strip()
    title_fs = 5.6 * sy * s1_scale
    c.setFont(active_font, title_fs)
    raw_title_w = c.stringWidth(p_name, active_font, title_fs)
    max_title_w = pw - (8.0 * sx)
    if raw_title_w > max_title_w and raw_title_w > 0:
        c.saveState()
        title_scale = min(100.0, (max_title_w / raw_title_w) * 100.0)
        t_title = c.beginText(4.0 * sx, 131.0 * sy)
        t_title.setFont(active_font, title_fs)
        t_title.setHorizScale(title_scale)
        t_title.textOut(p_name)
        c.drawText(t_title)
        c.restoreState()
    else:
        c.drawCentredString(pw / 2.0, 131.0 * sy, p_name)

